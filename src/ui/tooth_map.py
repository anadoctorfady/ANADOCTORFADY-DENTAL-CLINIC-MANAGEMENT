"""FDI tooth-number mapping (moved out of dental_chart.py, round 16,
so that module stays under 200 lines). Pure functions, no Tk."""

def tooth_type_for(n):
    """FDI number -> (kind, jaw). Deciduous teeth have no premolars
    (positions 4-5 are molars). None for an unknown number."""
    try:
        num, first = int(n), str(n)[0]
    except (TypeError, ValueError, IndexError):
        return None
    pos = num % 10
    if pos in (1, 2):
        kind = "incisor"
    elif pos == 3:
        kind = "canine"
    elif pos in (4, 5) and num < 51:
        kind = "premolar"
    elif pos in (4, 5, 6, 7, 8):
        kind = "molar"
    else:
        return None
    jaw = "upper" if first in "1256" else "lower"
    return kind, jaw


def tooth_image_name(n):
    """PNG file for an FDI number. Round 33: EVERY tooth has its own
    anatomically differentiated render, 'tooth_11.png' .. 'tooth_85.png'
    (no shared per-type images any more). Left-side teeth are true
    anatomical mirrors of the right-side renders - mesial side toward
    the midline - generated by convert_r33_teeth.py. None when the
    number is not a known FDI tooth."""
    if tooth_type_for(n) is None:
        return None
    return f"tooth_{int(n)}.png"


def display_order(nums, jaw):
    """Clinical display order (facing the patient): midline in the
    centre. Upper 18..11 | 21..28; lower 48..41 | 31..38; same rule
    for the deciduous rows."""
    half = len(nums) // 2
    left, right = nums[:half], nums[half:]
    if jaw == "upper":
        return list(reversed(left)) + list(right)
    return list(reversed(right)) + list(left)
